-- 목적: WF-2-4 / WF-3-8 보유종목 관리(ADD/DELETE/AVERAGE_DOWN)용 기본 스키마
-- 대상 DB: Oracle

CREATE TABLE TB_S_POSITION (
    POSITION_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    STOCK_GROUP      VARCHAR2(30)   NOT NULL,
    STOCK_CODE       VARCHAR2(20)   NOT NULL,
    MARKET_CODE      VARCHAR2(10)   DEFAULT 'KR' NOT NULL,
    TOTAL_QTY        NUMBER         DEFAULT 0 NOT NULL,
    AVG_PRICE        NUMBER         DEFAULT 0 NOT NULL,
    CLOSE_FLAG       VARCHAR2(1)    DEFAULT 'N' NOT NULL,
    STATE_CODE       VARCHAR2(30)   DEFAULT 'HOLD' NOT NULL,
    LAST_TXN_ID      NUMBER,
    MODIFY_DATE      DATE           DEFAULT SYSDATE NOT NULL,
    CREATE_USER      VARCHAR2(50),
    CREATE_DATE      DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_S_POSITION PRIMARY KEY (POSITION_ID)
);

CREATE UNIQUE INDEX UX_TB_S_POSITION_01 ON TB_S_POSITION (STOCK_GROUP, STOCK_CODE);
CREATE INDEX IX_TB_S_POSITION_01 ON TB_S_POSITION (STOCK_GROUP, STOCK_CODE, CLOSE_FLAG);
CREATE INDEX IX_TB_S_POSITION_02 ON TB_S_POSITION (STOCK_CODE, MODIFY_DATE);
CREATE INDEX IX_TB_S_POSITION_03 ON TB_S_POSITION (STATE_CODE, CLOSE_FLAG, MODIFY_DATE);

CREATE TABLE TB_S_POSITION_TXN (
    TXN_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    POSITION_ID      NUMBER,
    STOCK_GROUP      VARCHAR2(30)   NOT NULL,
    STOCK_CODE       VARCHAR2(20)   NOT NULL,
    ACTION_TYPE      VARCHAR2(20)   NOT NULL, -- ADD | DELETE | AVERAGE_DOWN | BUY | SELL
    QTY              NUMBER         DEFAULT 0 NOT NULL,
    PRICE            NUMBER         DEFAULT 0 NOT NULL,
    BEFORE_QTY       NUMBER,
    BEFORE_AVG       NUMBER,
    AFTER_QTY        NUMBER,
    AFTER_AVG        NUMBER,
    REASON_TEXT      VARCHAR2(1000),
    JSON_PARAMS      CLOB,
    CREATE_USER      VARCHAR2(50),
    CREATE_DATE      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_S_POSITION_TXN PRIMARY KEY (TXN_ID)
);

CREATE INDEX IX_TB_S_POSITION_TXN_01 ON TB_S_POSITION_TXN (STOCK_GROUP, STOCK_CODE, CREATE_DATE);
CREATE INDEX IX_TB_S_POSITION_TXN_02 ON TB_S_POSITION_TXN (POSITION_ID, CREATE_DATE);
CREATE INDEX IX_TB_S_POSITION_TXN_03 ON TB_S_POSITION_TXN (ACTION_TYPE, CREATE_DATE);

CREATE TABLE TB_S_POSITION_EVENT (
    EVENT_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    POSITION_ID      NUMBER,
    STOCK_GROUP      VARCHAR2(30),
    STOCK_CODE       VARCHAR2(20)   NOT NULL,
    EVENT_TYPE       VARCHAR2(40)   NOT NULL, -- ENTER | RISK_OFF | TREND_FOLLOW | EXIT | ALERT
    EVENT_LEVEL      VARCHAR2(20)   DEFAULT 'INFO' NOT NULL,
    EVENT_TIME       DATE           DEFAULT SYSDATE NOT NULL,
    MESSAGE          VARCHAR2(4000),
    JSON_PARAMS      CLOB,
    SOURCE_TXN_ID    NUMBER,
    CREATE_DATE      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_S_POSITION_EVENT PRIMARY KEY (EVENT_ID)
);

CREATE INDEX IX_TB_S_POSITION_EVENT_01 ON TB_S_POSITION_EVENT (STOCK_CODE, EVENT_TIME);
CREATE INDEX IX_TB_S_POSITION_EVENT_02 ON TB_S_POSITION_EVENT (POSITION_ID, EVENT_TIME);
CREATE INDEX IX_TB_S_POSITION_EVENT_03 ON TB_S_POSITION_EVENT (EVENT_TYPE, EVENT_TIME);
